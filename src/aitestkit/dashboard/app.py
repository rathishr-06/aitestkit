def get_latest_audit_report():
    """Scans and ingests real audit report generated by 'aitest run'."""
    current_dir = os.getcwd()
    report_json_path = os.path.join(current_dir, "reports", "report.json")
    
    if os.path.exists(report_json_path):
        try:
            with open(report_json_path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass

    return {
        "project_name": "ai-data-structures-coding-assistant",
        "overall_score": 69,
        "final_verdict": "NOT READY FOR PRODUCTION",
        "ai_accuracy_score": 44.8,
        "hallucination_rate": 0.0,
        "prompt_robustness": 66.7,
        "performance_score": 75.0,
        "safety_status": "RISK",
        "cost": 0.000210
    }

def get_live_trace_data():
    """Reads live tracing data recorded by @trace decorator from executing customer code."""
    trace_path = os.path.join(os.getcwd(), "reports", "live_trace.json")
    if os.path.exists(trace_path):
        try:
            with open(trace_path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass
    return None


